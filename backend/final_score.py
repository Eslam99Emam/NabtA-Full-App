import pandas as pd

temp_df = pd.read_csv("./Temp_results.csv")
temp_df

soil_df = pd.read_csv("./Soil_results.csv")
soil_df

result = pd.merge(temp_df, soil_df, on="ScientificName", how="inner")
result["score"] = (
    result["Temp_Score"] + result["texture"] + result["salinity"] + result["drainage"]
)
result = result.sort_values(by="score", ascending=False)
result.to_csv("final_score.csv")