import ee
import pandas as pd

# 1. Authenticate and Initialize Earth Engine
# (Colab will prompt you to log in with your Google account)
try:
    ee.Initialize()
except Exception as e:
    ee.Authenticate()
    ee.Initialize(project="nasa-agricultural-project")

# 2. Define your Farm Region of Interest (ROI)
# Example: A sample agricultural polygon in the Nile Delta/Cairo region
farm_polygon = ee.Geometry.Polygon(
    [[[31.20, 30.05], [31.25, 30.05], [31.25, 30.10], [31.20, 30.10]]]
)

# A. Soil Texture Class (USDA system at 0 cm surface depth)
texture_image = ee.Image("OpenLandMap/SOL/SOL_TEXTURE-CLASS_USDA-TT_M/v02").select("b0")

# B. Soil Water Retention / Drainage properties (e.g., Volumetric Water Content at 33kPa field capacity, 0-5cm depth)
water_content_image = ee.Image("ISRIC/SoilGrids250m/v2_0/wv0033").select(
    "val_0_5cm_mean"
)

# C. Global Soil Salinity Collection
salinity_collection = ee.ImageCollection(
    "projects/sat-io/open-datasets/global_soil_salinity"
).filterBounds(farm_polygon)


def extract_soil_properties():
    # 1. Reduce texture (categorical mode)
    texture_stats = texture_image.reduceRegion(
        reducer=ee.Reducer.mode(), geometry=farm_polygon, scale=250, maxPixels=1e9
    )

    # 2. Reduce water content / drainage proxy
    wc_stats = water_content_image.reduceRegion(
        reducer=ee.Reducer.mean(), geometry=farm_polygon, scale=250, maxPixels=1e9
    )

    # 3. Reduce salinity image
    salinity_img = salinity_collection.mean()
    salinity_stats = salinity_img.reduceRegion(
        reducer=ee.Reducer.mean(), geometry=farm_polygon, scale=30, maxPixels=1e9
    )

    # Wrap the results in an ee.Dictionary to evaluate server-side computations simultaneously
    return ee.Dictionary(
        {
            "soil_texture_class_b0": texture_stats.get("b0"),
            "volumetric_water_content_33kpa": wc_stats.get("val_0_5cm_mean"),
            "soil_salinity_proxy": salinity_stats.values().get(0),
        }
    )


# Run extraction and evaluate server-side dictionary to client-side Python dict
soil_results = extract_soil_properties().getInfo()

# Bring into a Pandas DataFrame for analysis
df_soil = pd.DataFrame([soil_results])
df_soil


def map_texture(b0_value):
    # Round to nearest integer USDA class (1-12)
    cls = round(b0_value)
    if cls in [1, 2, 3]:
        return "light"
    elif cls in [4, 5, 6, 7]:
        return "medium"
    elif cls in [8, 9, 10, 11, 12]:
        return "heavy"
    return "medium"  # default fallback


def map_drainage(vwc_value):
    if vwc_value < 0.20:
        return "excessive (dry/moderately dry)"
    elif vwc_value <= 0.40:
        return "well (dry spells)"
    else:
        return "poorly (saturated >50% of year)"


def map_salinity(sal_value):
    # Adjust thresholds based on whether your proxy is an index or actual dS/m
    if sal_value < 4:
        return "low (<4 dS/m)"
    elif sal_value <= 10:
        return "medium (4-10 dS/m)"
    else:
        return "high (>10 dS/m)"


# --- Step B: Extract Farm Conditions ---
# Assume df_soil contains your single row of extracted values from Earth Engine
# columns: 'soil_texture_class_b0', 'volumetric_water_content_33kpa', 'soil_salinity_proxy'

farm_conditions = {
    "texture": map_texture(df_soil["soil_texture_class_b0"].values[0]),
    "drainage": map_drainage(df_soil["volumetric_water_content_33kpa"].values[0]),
    "salinity": map_salinity(df_soil["soil_salinity_proxy"].values[0]),
}

print("Extracted Farm Profile:", farm_conditions)

df = pd.read_csv("./final_df.csv")
df.head(3)

result_data = {"ScientificName": [], "texture": [], "salinity": [], "drainage": []}

for i in df.itertuples(index=False):
    result_data["ScientificName"].append(i[1])
    # print(i[0])
    result_data["texture"].append(int(farm_conditions["texture"] in i[20]))
    # print(i[20], ' : ', farm_conditions['texture'], ' : ', result_data["texture"])
    result_data["salinity"].append(int(farm_conditions["salinity"] in i[22]))
    # print(i[22], ' : ', farm_conditions['salinity'], ' : ', result_data["salinity"])
    result_data["drainage"].append(int(farm_conditions["drainage"] in i[24]))
    # print(i[24], ' : ', farm_conditions['drainage'], ' : ', result_data["drainage"])

result_df = pd.DataFrame(result_data)
# result_df["score"] = result_df['texture'] + result_df['salinity'] + result_df['drainage']
result_df.to_csv("Soil_results.csv", index=False)
