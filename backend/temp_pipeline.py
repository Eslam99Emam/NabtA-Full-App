records = [
    {
        # Convert '202501' to pandas Period('2025-01', 'M') so .strftime("%Y-%m") works downstream
        "date": f"{k[:4]}-{k[4:6]}",
        "temperature_2m_c": v,
    }
    for k, v in t2m_dict.items()
    if not k.endswith("13") and v != -999
]

temp_monthly = pd.DataFrame(records)


def months_temp_rate(temps, topmn, topmx, tmin, tmax, months):
    result = {}
    scores = []
    # print(temps)
    # print(months)
    for t in temps:
        if topmn < t < topmx:
            score = 1.0
        elif tmin < t < topmn:
            # denominator = topmn - tmin
            # print(t)
            score = (t - tmin) / (topmn - tmin)
            # print(score)
        elif tmax > t > topmx:
            denominator = tmax - topmx
            score = (t - topmx) / denominator if denominator != 0 else 0.0
        else:
            score = 1.0
        scores.append(score)
    # print(scores)
    for m, s in zip(months, scores):
        result[m] = s
    return result


